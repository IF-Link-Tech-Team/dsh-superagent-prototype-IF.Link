/** The emoji ids in the order Feishu's documentation lists them. */
export const FEISHU_EMOJI_IDS: readonly string[] = Object.keys(FEISHU_EMOJIS)
/** The ones a working message may wear, which a Channel falls back to when a model answers with something else. */
export const FEISHU_WORK_EMOJIS: readonly string[] = FEISHU_EMOJI_IDS.filter(id => FEISHU_EMOJIS[id]!.work)
/** Whether `id` names emoji this Channel can add, exactly as the API spells it. */
export const isFeishuEmoji = (id: string): boolean => Object.hasOwn(FEISHU_EMOJIS, id)
